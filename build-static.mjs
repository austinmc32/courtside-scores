// Build the static, server-less variant into docs/ for GitHub Pages.
//
// GitHub Pages serves files only, so the app calls the upstream feeds directly
// instead of going through the Node/Worker proxy. Both upstreams send
// `Access-Control-Allow-Origin: *`, so the browser is allowed to call them.
// Re-run after editing anything in public/.
//
// Run: node build-static.mjs

import { readFile, writeFile, mkdir, rm, cp } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const out = join(root, 'docs');

const UPSTREAM_CONFIG = `// Static build: call the upstream feeds directly (both send CORS headers), so
// this runs with no server. Generated by build-static.mjs - edit public/ instead.
const ESPN='https://site.api.espn.com/apis/site/v2';
const WATCH='https://streamed.pk/api';
const ESPN_LEAGUES={nba:'basketball/nba',wnba:'basketball/wnba',nfl:'football/nfl',mlb:'baseball/mlb',nhl:'hockey/nhl',epl:'soccer/eng.1',mls:'soccer/usa.1'};
const SPORT={nba:'basketball',wnba:'basketball',nfl:'american-football',mlb:'baseball',nhl:'hockey',epl:'football',mls:'football'};
`;

const LEAGUES_LINE = "const leagues={nba:['NBA','🏀']";

// Each entry must match exactly once; a silent miss would ship a broken app.
const APP_REWRITES = [
  ['`/api/scoreboard?league=${league}&date=${date}`',
   '`${ESPN}/sports/${ESPN_LEAGUES[league]}/scoreboard?dates=${date}&limit=100`'],
  ['`/api/summary?league=${encodeURIComponent(game.league)}&event=${encodeURIComponent(game.id)}`',
   '`${ESPN}/sports/${ESPN_LEAGUES[game.league]}/summary?event=${encodeURIComponent(game.id)}`'],
  ['`/api/watch/matches?league=${game.league}`',
   '`${WATCH}/matches/${SPORT[game.league]}`'],
  ['`/api/watch/matches?league=${league}`',
   '`${WATCH}/matches/${SPORT[league]}`'],
  ['`/api/watch/streams?source=${encodeURIComponent(s.source)}&id=${encodeURIComponent(s.id)}`',
   '`${WATCH}/stream/${encodeURIComponent(s.source)}/${encodeURIComponent(s.id)}`']
];

function rewriteApp(source) {
  const anchor = source.indexOf(LEAGUES_LINE);
  if (anchor === -1) throw new Error('leagues line not found in app.js');
  const eol = source.indexOf('\n', anchor) + 1;
  let out = source.slice(0, eol) + UPSTREAM_CONFIG + source.slice(eol);
  for (const [from, to] of APP_REWRITES) {
    const count = out.split(from).length - 1;
    if (count !== 1) throw new Error(`expected 1 match for ${from}, found ${count}`);
    out = out.replace(from, to);
  }
  const leftover = out.match(/\/api\//);
  if (leftover) throw new Error('an /api/ reference survived the rewrite');
  return out;
}

function rewriteHtml(source) {
  let out = source
    .replace('href="/style.css"', 'href="style.css"')
    .replace('src="/app.js"', 'src="app.js"')
    .replace('href="/"', 'href="./"');
  if (/["']\/[a-z]/i.test(out)) throw new Error('an absolute path survived the html rewrite');
  return out;
}

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

const app = await readFile(join(root, 'public', 'app.js'), 'utf8');
const html = await readFile(join(root, 'public', 'index.html'), 'utf8');

await writeFile(join(out, 'app.js'), rewriteApp(app));
await writeFile(join(out, 'index.html'), rewriteHtml(html));
await cp(join(root, 'public', 'scoreboard-view.js'), join(out, 'scoreboard-view.js'));
await cp(join(root, 'public', 'style.css'), join(out, 'style.css'));
// Pages serves 404.html for unknown paths; keep the SPA reachable.
await writeFile(join(out, '.nojekyll'), '');

console.log('built docs/ (index.html, app.js, scoreboard-view.js, style.css)');
